"""Package the generated classroom art and trace its island silhouettes.

Usage: python scripts/build-map-art.py INPUTS.json ASSET_DIR

INPUTS maps classroom-selection and each theme's -background and -islands to source
images. The selection image has three side-by-side rooms. Each transparent island
sheet has five level islands followed by three minigames in a 4 x 2 grid.
Requires Pillow, numpy and opencv-python.
"""
import argparse
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageOps

THEMES = ('arithmetic', 'geometry', 'algebra')
NODES = tuple([f'level-{i}' for i in range(1, 6)] + [f'minigame-{i}' for i in range(1, 4)])
ISLAND_SIZE = (240, 258)
ISLAND_PADDING = 12
ALPHA_THRESHOLD = 96


def clean_cutout(cell):
    alpha = np.array(cell.getchannel('A'))
    count, components, stats, _ = cv2.connectedComponentsWithStats((alpha >= ALPHA_THRESHOLD).astype('uint8'))
    if count <= 1:
        raise ValueError('Empty island cell')
    areas = stats[1:, cv2.CC_STAT_AREA]
    keep = np.flatnonzero(areas >= areas.max() * 0.02) + 1
    core = np.isin(components, keep).astype('uint8')
    edge = cv2.dilate(core, np.ones((3, 3), dtype='uint8'))
    cell.putalpha(Image.fromarray(alpha * edge))
    return cell.crop(cell.getbbox())


def pack_island(cell):
    source = clean_cutout(cell)
    width, height = ISLAND_SIZE
    fit = ImageOps.contain(source, (width - 2 * ISLAND_PADDING, height - 2 * ISLAND_PADDING),
                           method=Image.Resampling.LANCZOS)
    image = Image.new('RGBA', ISLAND_SIZE)
    x = (width - fit.width) // 2
    y = height - ISLAND_PADDING - fit.height
    image.alpha_composite(fit, (x, y))

    mask = (np.array(image.getchannel('A')) >= ALPHA_THRESHOLD).astype('uint8')
    contours, _ = cv2.findContours(mask, cv2.RETR_TREE, cv2.CHAIN_APPROX_SIMPLE)
    pieces = []
    for contour in contours:
        if cv2.contourArea(contour) < 6:
            continue
        points = cv2.approxPolyDP(contour, 0.65, True).reshape(-1, 2)
        if len(points) < 3:
            continue
        first, *remaining = [f'{x},{y}' for x, y in points]
        pieces.append('M' + first + 'L' + ' '.join(remaining) + 'Z')
    if not pieces:
        raise ValueError('Island has no traceable outline')
    deck = round((y + fit.height * 0.62) / height, 4)
    return image, ''.join(pieces), deck


def package(inputs, output):
    output.mkdir(parents=True, exist_ok=True)
    declarations = [
        '// Generated by scripts/build-map-art.py. Each hit path follows its matching alpha silhouette.',
        'export interface IslandArtwork { readonly src: string; readonly path: string; readonly deck: number; }',
        'export interface ClassroomArtwork {',
        '  readonly preview: string;',
        '  readonly background: string;',
        '  readonly islands: readonly IslandArtwork[];',
        '}',
        '',
        f'export const MAP_ISLAND_SIZE = {{ width: {ISLAND_SIZE[0]}, height: {ISLAND_SIZE[1]} }} as const;',
        'export const MAP_ART: readonly ClassroomArtwork[] = [',
    ]

    def url(path):
        return f"new URL('./{path}', import.meta.url).href"

    with Image.open(inputs['classroom-selection']) as source:
        triptych = source.convert('RGB')
    for room, theme in enumerate(THEMES):
        folder = output / theme
        folder.mkdir(exist_ok=True)
        left = round(triptych.width * room / 3)
        right = round(triptych.width * (room + 1) / 3)
        preview = triptych.crop((left, 0, right, triptych.height))
        ImageOps.fit(preview, (640, 800), method=Image.Resampling.LANCZOS).save(folder / 'classroom.webp', quality=88)
        with Image.open(inputs[theme + '-background']) as source:
            background = ImageOps.fit(source.convert('RGB'), (1600, 900), method=Image.Resampling.LANCZOS)
        background.save(folder / 'dream.webp', quality=88)

        with Image.open(inputs[theme + '-islands']) as source:
            if 'A' not in source.getbands() or source.getchannel('A').getextrema()[0] >= ALPHA_THRESHOLD:
                raise ValueError(f'{theme} island sheet needs a transparent canvas')
            sheet = source.convert('RGBA')
        declarations.extend([
            '  {',
            f'    preview: {url(theme + "/classroom.webp")},',
            f'    background: {url(theme + "/dream.webp")},',
            '    islands: [',
        ])
        for index, node in enumerate(NODES):
            row, col = divmod(index, 4)
            box = (round(sheet.width * col / 4), round(sheet.height * row / 2),
                   round(sheet.width * (col + 1) / 4), round(sheet.height * (row + 1) / 2))
            art, contour, deck = pack_island(sheet.crop(box))
            art.save(folder / (node + '.webp'), quality=90)
            declarations.append(
                f'      {{ src: {url(theme + "/" + node + ".webp")}, path: {json.dumps(contour)}, deck: {deck} }},'
            )
        declarations.extend(['    ],', '  },'])
        print(f'{theme}: classroom, dream, and {len(NODES)} island silhouettes')
    declarations.extend(['];', ''])
    (output / 'index.ts').write_text('\n'.join(declarations), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('inputs', type=Path)
    parser.add_argument('output', type=Path)
    arguments = parser.parse_args()
    package(json.loads(arguments.inputs.read_text(encoding='utf-8-sig')), arguments.output)
